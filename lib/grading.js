// ============================================================
// 점수와 등급
//
// 두 숫자를 따로 낸다. 섞으면 의미가 없어진다.
//
//   스캔률 = 본 것 / 볼 수 있었던 것      → "얼마나 넓게 봤나"
//   품질점수 = 통과한 것 / 본 것 (가중)   → "본 것 중 얼마나 멀쩡한가"
//
// 가중치는 "틀렸을 때 사장님이 입는 피해" 순서다.
// 돈이 틀리는 것(M·X·Y)과 남의 정보가 새는 것(C·I·K)이 가장 무겁고,
// 문구가 어색한 것(U)이나 로그(L)는 가볍다.
// ============================================================

// 등급 기준 — 대기업 홈페이지를 100 으로 놓았을 때
//
// 100 을 무엇으로 잡았는지부터 밝힌다. 그래야 60 이 무슨 뜻인지 말이 된다.
// 여기서 '대기업 수준'은 아래를 **전부** 갖춘 상태다.
//   · 26개 영역 전부에 자동 검사가 있고 CI 에서 매 배포마다 돈다
//   · 취약점 점검·부하 시험·접근성 점검이 별도 조직에서 정기적으로 돈다
//   · 장애를 사람이 발견하기 전에 감시 시스템이 먼저 알린다
//   · 개인정보 처리 방침·보관 기한·감사 로그가 법적 기준에 맞춰 관리된다
// 즉 100 은 "버그가 없다"가 아니라 "빠뜨릴 구조가 아니다" 이다.
//
// 구간은 이렇게 나눈다.
const GRADES = [
  { min: 90, label: '대기업 수준',  desc: '26개 영역 전부 자동 검사 + CI + 상시 감시. 사람이 빠뜨릴 구조가 아니다.' },
  { min: 75, label: '중급 상위',    desc: '돈·권한·개인정보처럼 아픈 곳은 자동 검사로 지킨다. 감시와 부하 시험이 없다.' },
  { min: 60, label: '중급',         desc: '주요 흐름은 돌고 큰 구멍은 없다. 검사는 사람이 기억해서 돌린다.' },
  { min: 45, label: '초급 상위',    desc: '기능은 다 되지만 검사가 눈으로 하는 수준. 고치면 다른 데가 깨지는지 모른다.' },
  { min: 30, label: '초급',         desc: '만든 사람만 쓸 수 있는 상태. 돈이나 권한이 틀려도 한참 뒤에 안다.' },
  { min: 0,  label: '미완성',       desc: '주요 흐름이 끊겨 있다.' },
];

// 수준별 기대 점수대 — "우리가 어디쯤인가"를 말하려면 남의 자리도 정해야 한다
const TIERS = {
  '대기업':  { min: 90, max: 100, note: '네이버·카카오·토스 같은 곳의 서비스. 전담 QA 조직과 CI 가 있다.' },
  '중급':    { min: 60, max: 89,  note: '개발자 몇 명이 붙은 스타트업·중소기업 제품. 아픈 곳만 자동 검사.' },
  '초급':    { min: 30, max: 59,  note: '1인 개발·외주 납품 직후. 기능은 되지만 회귀 검사가 없다.' },
  '미완성':  { min: 0,  max: 29,  note: '개발 중이거나 주요 흐름이 끊긴 상태.' },
};

function gradeOf(score) {
  return GRADES.find(g => score >= g.min);
}

function tierOf(score) {
  for (const [name, t] of Object.entries(TIERS)) if (score >= t.min && score <= t.max) return name;
  return '미완성';
}

module.exports = { GRADES, TIERS, gradeOf, tierOf };
